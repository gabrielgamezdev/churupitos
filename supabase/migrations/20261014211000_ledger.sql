-- Las funciones de saldos corren con los permisos de quien pregunta (no son
-- `security definer`), y la vista también (`security_invoker`): el RLS de las
-- tablas decide lo que ven.
revoke all on public.accounts, public.envelopes, public.operations, public.entries,
  public.account_ledger from anon, authenticated;
grant select on public.accounts, public.envelopes, public.operations, public.entries,
  public.account_ledger to authenticated;

revoke execute on function
  public.cell_balances(date), public.account_balances(date),
  public.envelope_balances(date), public.currency_totals(date)
  from public, anon;
grant execute on function
  public.cell_balances(date), public.account_balances(date),
  public.envelope_balances(date), public.currency_totals(date)
  to authenticated;

