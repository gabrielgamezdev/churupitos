-- El libro: cuentas, sobres, operaciones y asientos, y los saldos que salen de ellos.
-- Las reglas que se citan (R1, R5…) son las de docs/DOMINIO.md.
--
-- En M1 la app solo lee: las escrituras las hace el importador con el rol de la
-- base, que no pasa por RLS. Los permisos de escritura llegan con M6.

-- ---------------------------------------------------------------------------
-- Cuentas y sobres
-- ---------------------------------------------------------------------------

create table public.accounts (
  id uuid primary key default gen_random_uuid(),
  name text not null unique check (length(trim(name)) between 1 and 40),
  -- R3: una sola moneda por cuenta, y los asientos la heredan de aquí.
  currency text not null check (currency in ('VES', 'USD')),
  -- El orden de las hojas en el Excel.
  position smallint not null default 0,
  created_at timestamptz not null default now()
);

create table public.envelopes (
  id uuid primary key default gen_random_uuid(),
  name text not null unique check (length(trim(name)) between 1 and 40),
  -- R11: «Otro» es el dinero ajeno que pasa por las cuentas. Los totales «sin
  -- Otro» lo restan. Como mucho hay uno (D6).
  is_third_party boolean not null default false,
  -- El orden de los sobres en el presupuesto del Excel.
  position smallint not null default 0,
  created_at timestamptz not null default now()
);

create unique index envelopes_single_third_party
  on public.envelopes (is_third_party)
  where is_third_party;

-- ---------------------------------------------------------------------------
-- Operaciones y asientos
-- ---------------------------------------------------------------------------

create table public.operations (
  id uuid primary key default gen_random_uuid(),
  kind text not null check (kind in (
    'expense', 'income', 'envelope_transfer', 'account_transfer', 'exchange', 'adjustment'
  )),
  -- R13: la fecha ya es la de Caracas; sin hora, no hay zona que la mueva de día.
  occurred_on date not null,
  -- R15: la fila no tenía fecha y se tomó la de la anterior.
  date_approximate boolean not null default false,
  description text not null default '',
  adjustment_reason text check (adjustment_reason in (
    'opening', 'carry_reassignment', 'interest', 'correction'
  )),
  -- Vacío en lo importado: el Excel no dice quién escribió cada fila.
  created_by uuid default auth.uid() references public.household_members (user_id),
  created_at timestamptz not null default now(),
  -- Un ajuste no tiene contraparte, así que el motivo es lo único que lo explica.
  constraint operations_reason_only_on_adjustment_check
    check ((kind = 'adjustment') = (adjustment_reason is not null))
);

create index operations_occurred_on_idx on public.operations (occurred_on);

create table public.entries (
  id uuid primary key default gen_random_uuid(),
  operation_id uuid not null references public.operations (id) on delete cascade,
  account_id uuid not null references public.accounts (id),
  envelope_id uuid not null references public.envelopes (id),
  -- R1: céntimos con signo, negativo sale. R4: nunca cero.
  amount_cents bigint not null check (amount_cents <> 0),
  -- R16: una comisión es un asiento propio, y siempre sale dinero.
  is_fee boolean not null default false,
  -- El concepto de la fila del Excel. Vacío: vale el de la operación.
  description text not null default '',
  -- R14: el orden dentro del día. El importador pone la fila del Excel; lo que se
  -- registre en la app toma el siguiente de la secuencia.
  position bigint generated by default as identity,
  constraint entries_fee_is_negative_check check (not is_fee or amount_cents < 0)
);

create index entries_operation_id_idx on public.entries (operation_id);
create index entries_account_id_idx on public.entries (account_id);
create index entries_envelope_id_idx on public.entries (envelope_id);

-- ---------------------------------------------------------------------------
-- R5: cada operación cumple el invariante de su tipo
-- ---------------------------------------------------------------------------

-- Mira una operación entera y lanza un error si no cumple su invariante. Los
-- asientos de comisión no cuentan (DOMINIO.md §3). Una operación que ya no existe
-- se da por buena: se borró en la misma transacción.
create function public.assert_operation_shape(target uuid)
returns void
language plpgsql
stable
set search_path = ''
as $$
declare
  op_kind text;
  entry_count integer;
  line_count integer;
  account_count integer;
  currency_count integer;
  all_negative boolean;
  all_positive boolean;
  line_sum bigint;
  problem text;
begin
  select kind into op_kind from public.operations where id = target;
  if not found then
    return;
  end if;

  select
    count(*),
    count(*) filter (where not e.is_fee),
    count(distinct e.account_id) filter (where not e.is_fee),
    count(distinct a.currency) filter (where not e.is_fee),
    coalesce(bool_and(e.amount_cents < 0) filter (where not e.is_fee), true),
    coalesce(bool_and(e.amount_cents > 0) filter (where not e.is_fee), true),
    coalesce(sum(e.amount_cents) filter (where not e.is_fee), 0)
  into entry_count, line_count, account_count, currency_count, all_negative, all_positive, line_sum
  from public.entries e
  join public.accounts a on a.id = e.account_id
  where e.operation_id = target;

  if entry_count = 0 then
    problem := 'Una operación necesita al menos un asiento';

  elsif op_kind = 'expense' then
    if account_count > 1 then
      problem := 'Un gasto sale de una sola cuenta';
    elsif not all_negative then
      problem := 'En un gasto todos los importes son negativos';
    end if;

  elsif op_kind = 'income' then
    if line_count = 0 then
      problem := 'Un ingreso necesita al menos un importe que no sea comisión';
    elsif account_count > 1 then
      problem := 'Un ingreso entra en una sola cuenta';
    elsif not all_positive then
      problem := 'En un ingreso todos los importes son positivos';
    end if;

  elsif op_kind = 'envelope_transfer' then
    -- El dinero no se mueve de cuenta: en cada una, lo que sale de un sobre entra
    -- en otro.
    if line_count = 0 or exists (
      select 1
      from public.entries e
      where e.operation_id = target and not e.is_fee
      group by e.account_id
      having sum(e.amount_cents) <> 0
    ) then
      problem := 'Un movimiento entre sobres tiene que sumar cero en cada cuenta';
    end if;

  elsif op_kind = 'account_transfer' then
    if currency_count <> 1 then
      problem := 'Un traspaso entre cuentas es de una sola moneda';
    elsif account_count < 2 then
      problem := 'Un traspaso entre cuentas necesita al menos dos cuentas';
    elsif line_sum <> 0 then
      problem := 'Un traspaso entre cuentas tiene que sumar cero';
    end if;

  elsif op_kind = 'exchange' then
    -- En una moneda sale dinero y en la otra entra. La tasa no se valida: es la
    -- que fue, y se deriva de los dos importes.
    if currency_count <> 2 then
      problem := 'Un cambio de divisa tiene que tener las dos monedas';
    elsif (
      select count(*) filter (where s.total < 0) <> 1 or count(*) filter (where s.total > 0) <> 1
      from (
        select sum(e.amount_cents) as total
        from public.entries e
        join public.accounts a on a.id = e.account_id
        where e.operation_id = target and not e.is_fee
        group by a.currency
      ) s
    ) then
      problem := 'En un cambio de divisa sale una moneda y entra la otra';
    end if;
  end if;
  -- Un ajuste no tiene invariante: lo justifica su motivo, que exige la tabla.

  if problem is not null then
    raise exception '%', problem
      using errcode = 'check_violation', detail = format('operación %s (%s)', target, op_kind);
  end if;
end;
$$;

revoke execute on function public.assert_operation_shape(uuid) from public, anon;
grant execute on function public.assert_operation_shape(uuid) to authenticated;

create function public.check_operation_shape()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if tg_table_name = 'operations' then
    perform public.assert_operation_shape(new.id);
  else
    if tg_op <> 'INSERT' then
      perform public.assert_operation_shape(old.operation_id);
    end if;
    if tg_op <> 'DELETE' then
      perform public.assert_operation_shape(new.operation_id);
    end if;
  end if;
  return null;
end;
$$;

-- Diferidos: una operación se escribe en varias sentencias (la cabecera y luego sus
-- asientos), y solo tiene sentido comprobarla entera, al confirmar la transacción.
create constraint trigger operations_check_shape
  after insert or update of kind on public.operations
  deferrable initially deferred
  for each row execute function public.check_operation_shape();

create constraint trigger entries_check_shape
  after insert or update or delete on public.entries
  deferrable initially deferred
  for each row execute function public.check_operation_shape();

-- ---------------------------------------------------------------------------
-- Saldos (R2): nada se guarda, todo se suma al leer
-- ---------------------------------------------------------------------------

-- Cada función da el saldo al cierre del día `as_of`, o de todo el libro si es
-- nulo. Así el arrastre entre meses (R7) no existe como dato: el saldo de apertura
-- de un mes es el de cierre del día anterior. Las demás funciones salen de esta,
-- para que haya una sola forma de sumar.
create function public.cell_balances(as_of date default null)
returns table (account_id uuid, envelope_id uuid, currency text, balance_cents bigint)
language sql
stable
set search_path = ''
as $$
  select e.account_id, e.envelope_id, a.currency, sum(e.amount_cents)::bigint
  from public.entries e
  join public.operations o on o.id = e.operation_id
  join public.accounts a on a.id = e.account_id
  where as_of is null or o.occurred_on <= as_of
  group by e.account_id, e.envelope_id, a.currency;
$$;

-- Todas las cuentas, también las que no tienen movimientos.
create function public.account_balances(as_of date default null)
returns table (account_id uuid, name text, currency text, "position" smallint, balance_cents bigint)
language sql
stable
set search_path = ''
as $$
  select a.id, a.name, a.currency, a.position, coalesce(sum(c.balance_cents), 0)::bigint
  from public.accounts a
  left join public.cell_balances(as_of) c on c.account_id = a.id
  group by a.id;
$$;

-- Un sobre tiene un saldo en cada moneda en la que tenga dinero.
create function public.envelope_balances(as_of date default null)
returns table (envelope_id uuid, currency text, balance_cents bigint)
language sql
stable
set search_path = ''
as $$
  select c.envelope_id, c.currency, sum(c.balance_cents)::bigint
  from public.cell_balances(as_of) c
  group by c.envelope_id, c.currency;
$$;

-- Los totales de la portada, por moneda. R11: lo propio es el total menos «Otro».
create function public.currency_totals(as_of date default null)
returns table (currency text, total_cents bigint, third_party_cents bigint, own_cents bigint)
language sql
stable
set search_path = ''
as $$
  select
    a.currency,
    coalesce(sum(c.balance_cents), 0)::bigint,
    coalesce(sum(c.balance_cents) filter (where v.is_third_party), 0)::bigint,
    coalesce(sum(c.balance_cents) filter (where not v.is_third_party), 0)::bigint
  from public.accounts a
  left join public.cell_balances(as_of) c on c.account_id = a.id
  left join public.envelopes v on v.id = c.envelope_id
  group by a.currency;
$$;

-- El libro de cada cuenta, como su hoja del Excel: el restante corrido después de
-- cada asiento (R14). Se puede filtrar por cuenta o por fecha sin romper el
-- corrido: Postgres suma el libro entero de la cuenta antes de aplicar el filtro.
create view public.account_ledger
with (security_invoker = true)
as
select
  e.id as entry_id,
  e.operation_id,
  e.account_id,
  a.currency,
  o.occurred_on,
  o.date_approximate,
  e.position,
  o.kind,
  e.envelope_id,
  e.amount_cents,
  e.is_fee,
  e.description,
  o.description as operation_description,
  sum(e.amount_cents) over (
    partition by e.account_id
    order by o.occurred_on, e.position, e.id
  )::bigint as running_balance_cents
from public.entries e
join public.operations o on o.id = e.operation_id
join public.accounts a on a.id = e.account_id;

